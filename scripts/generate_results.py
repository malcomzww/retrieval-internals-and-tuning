TENANT_WIDTHS = (32, 16, 8, 4, 2, 1)
BUDGETS_MS = (0.2, 0.5, 1.0, 2.0, 5.0, 10.0, 20.0, 50.0, 100.0, 200.0, 500.0, 1500.0)


