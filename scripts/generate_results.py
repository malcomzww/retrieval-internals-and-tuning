        f"# {title}\n",
        "Generated by `python scripts/generate_results.py`. Do not edit by hand.\n",
        f"- Date: {date.today().isoformat()}",
        f"- Corpus: {N_DOCS:,} synthetic passages, k={K}, {n_queries} queries",
        f"- Embedder: {embedder}",
        f"- Hardware: 24-core CPU, 32 GB RAM, no GPU "
        f"({platform.system()} {platform.machine()}, Python {platform.python_version()})",
