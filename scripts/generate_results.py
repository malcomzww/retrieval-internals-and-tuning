"""Generate every number this repo reports.

Output is split the way `llm-client-kit` splits it, and for the same reason:

- ``results/*.md``      committed. Recall, orderings, crossovers, and ratios --
                        quantities that reproduce on any machine. CI regenerates
                        these and fails if they drift.
- ``results/*-raw.md``  gitignored. Absolute millisecond timings from whatever
                        machine happened to run it.

The split is not fastidiousness. Recall here is exact: it is measured against
an exhaustive scan of the same vectors, so it reproduces bit-for-bit anywhere.
Latency is a wall-clock measurement on a non-realtime OS with a shared cache,
and byte-comparing milliseconds across machines is a gate that fails for no
useful reason. So the committed files carry claims of the form "A is faster
than B" and "the crossover is between X and Y", and the raw file carries the
numbers those claims were derived from.

Every committed claim is asserted before any file is written. If a claim stops
holding, this script exits non-zero rather than emitting a report that states
it.

Run:  python scripts/generate_results.py
      python scripts/generate_results.py --quick   (smaller, skips cross-encoder)
"""

